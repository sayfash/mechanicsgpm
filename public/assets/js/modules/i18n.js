function t(key, defaultStr = '') {
    const lang = (typeof getAppLanguage === 'function' ? getAppLanguage() : 'en');
    const entry = i18nDictionary[key];
    if (entry && entry[lang]) {
        return entry[lang];
    }

    // Direct string lookup fallback for static UI elements
    if (window.staticUiMap) {
        if (lang === 'id') {
            if (staticUiMap[key]) return staticUiMap[key];
            if (staticUiMap[defaultStr]) return staticUiMap[defaultStr];
        } else if (lang === 'en') {
            // Reverse lookup ID -> EN
            for (const enKey in staticUiMap) {
                if (staticUiMap[enKey] === key || staticUiMap[enKey] === defaultStr) {
                    return enKey;
                }
            }
        }
    }

    return defaultStr || (entry ? entry[lang] : key);
}
window.t = t;
window.staticUiMap = staticUiMap;
window.i18nDictionary = i18nDictionary;
